<?php

namespace App\Models;

use App\Models\Concerns\BelongsToTenant;
use App\Models\Concerns\HasDocumentNumber;
use App\Models\Concerns\LogsAuditActivity;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * A physical fabric roll ("than") of a fabric product, tracked with textile
 * attributes (GSM, width, shade, dye lot) and a running remaining length.
 *
 * Lifecycle (length-driven): available → partial (some cut) → consumed
 * (nothing left). An inspection reject can quarantine a roll; a roll may also
 * be scrapped. Leftover rolls are remnants generated by a cutting operation
 * (is_leftover = true, parent_roll_id set).
 */
class FabricRoll extends Model
{
    use BelongsToTenant, HasDocumentNumber, LogsAuditActivity;

    protected static string $numberSettingKey = 'roll_number_prefix';

    protected $fillable = [
        'roll_number', 'product_id', 'variant_id', 'warehouse_id', 'supplier_id',
        'shade_no', 'dye_lot', 'gsm', 'width', 'width_unit', 'length_unit',
        'initial_length', 'current_length', 'unit_cost', 'grade', 'status',
        'is_leftover', 'parent_roll_id', 'posted_to_stock', 'received_date',
        'notes', 'created_by',
    ];

    protected $casts = [
        'gsm' => 'decimal:2',
        'width' => 'decimal:2',
        'initial_length' => 'decimal:3',
        'current_length' => 'decimal:3',
        'unit_cost' => 'decimal:4',
        'is_leftover' => 'boolean',
        'posted_to_stock' => 'boolean',
        'received_date' => 'date',
    ];

    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class);
    }

    public function variant(): BelongsTo
    {
        return $this->belongsTo(ProductVariant::class, 'variant_id');
    }

    public function warehouse(): BelongsTo
    {
        return $this->belongsTo(Warehouse::class);
    }

    public function supplier(): BelongsTo
    {
        return $this->belongsTo(Supplier::class);
    }

    public function parentRoll(): BelongsTo
    {
        return $this->belongsTo(FabricRoll::class, 'parent_roll_id');
    }

    public function inspections(): HasMany
    {
        return $this->hasMany(FabricInspection::class);
    }

    public function cuttings(): HasMany
    {
        return $this->hasMany(FabricCutting::class);
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /** Consumed length so far: initial − current (clamped at zero). */
    public function getConsumedLengthAttribute(): float
    {
        return round(max(0, (float) $this->initial_length - (float) $this->current_length), 3);
    }

    /**
     * Recompute the length-driven status. Quarantined and scrapped are manual
     * terminal states this helper leaves untouched.
     */
    public function refreshStatus(): void
    {
        if (in_array($this->status, ['quarantined', 'scrapped'], true)) {
            return;
        }

        if ((float) $this->current_length <= 0.0001) {
            $this->status = 'consumed';
        } elseif ((float) $this->current_length < (float) $this->initial_length - 0.0001) {
            $this->status = 'partial';
        } else {
            $this->status = 'available';
        }

        $this->save();
    }
}
