const DICTS: Record<string, Record<string, string>> = { hi, gu }

/** Translate a DB menu label into the active UI language (English fallback). */
export function translateMenuLabel(label: string): string {
  const dict = DICTS[i18n.global.locale.value as string]
  return dict?.[label] ?? label
}

/** Reactive helper for templates: `const tMenu = useMenuLabel()`. */
export function useMenuLabel() {
  // Touch the locale ref inside a computed so callers re-render on switch.
  const localeRef = computed(() => i18n.global.locale.value)
  return (label: string): string => {
    const dict = DICTS[localeRef.value as string]
    return dict?.[label] ?? label
  }
}
